import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { chromium } from 'playwright'
const base = process.env.HOME_BASE_URL || 'http://127.0.0.1:5174'
const output = resolve('.playwright-mcp/home-redesign')
await mkdir(output, { recursive: true })
const site = JSON.parse(await readFile('src/seo/site.json', 'utf8'))
const routes = new Set(site.routes.map(item => item.path))
const browser = await chromium.launch({ executablePath: process.env.PRERENDER_CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const errors = []
try {
  for (const width of [320, 375, 768, 1024, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    page.on('pageerror', e => errors.push(e.message))
    await page.addInitScript(() => sessionStorage.setItem('dpdpa_modal_dismissed', 'true'))
    await page.goto(base + '/', { waitUntil: 'domcontentloaded' })
    await page.locator('.hm-page').waitFor()
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.locator('h1').count(), 1)
    assert.equal(await page.locator('footer').count(), 1)
    assert.equal(await page.locator('iframe').count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
    const hero = await page.locator('.hm-hero').evaluate(root => {
      const heading = root.querySelector('h1').getBoundingClientRect(), video = root.querySelector('video').getBoundingClientRect()
      return { headingCenter: heading.x + heading.width / 2, videoCenter: video.x + video.width / 2, videoTop: video.top, headingBottom: heading.bottom, paused: root.querySelector('video').paused, font: getComputedStyle(root.querySelector('h1')).fontFamily }
    })
    assert.ok(Math.abs(hero.headingCenter - width / 2) < 2, 'Centered headline')
    assert.ok(Math.abs(hero.videoCenter - width / 2) < 2, 'Centered video')
    assert.ok(hero.videoTop > hero.headingBottom, 'Video below headline')
    assert.ok(hero.paused, 'Video waits for user interaction')
    assert.ok(hero.font.includes('Manrope'), 'Existing BNC typography')
    assert.equal(await page.locator('.ob-cell').count(), 0, 'No hero pointer effect')
    assert.equal(await page.locator('.ob-shine').evaluate(e => getComputedStyle(e).animationName), 'none')
    for (const name of ['india_saudi_corridor', 'reviewing_financial_reports', 'icon_accounting', 'icon_tax', 'icon_advisory']) assert.ok(await page.locator(`.hm-page img[src*="${name}"]`).count(), name + ' retained')
    const challenge = page.getByRole('region', { name: 'Business challenges', exact: true })
    for (const [title, percentage] of [['Resistance to change', 95], ['Security Controls', 81], ['Regulatory Challenges', 88], ['Merger integration', 89]]) {
      await page.getByRole('button', { name: 'Show challenge: ' + title, exact: true }).click()
      assert.equal(await challenge.getByRole('heading', { name: title, exact: true }).count(), 1)
      assert.equal(await page.locator('.hm-challenge-percentage').innerText(), percentage + '%')
    }
    await page.getByRole('button', { name: 'Next challenge', exact: true }).click()
    assert.equal(await challenge.getByRole('heading', { name: 'Resistance to change', exact: true }).count(), 1)
    const general = page.getByRole('tab', { name: 'General', exact: true })
    await general.click()
    assert.equal(await general.getAttribute('aria-selected'), 'true')
    const search = page.getByRole('searchbox', { name: 'Search frequently asked questions' })
    await search.fill('software')
    const panel = page.getByRole('tabpanel')
    assert.equal(await panel.locator('details').count(), 1)
    await panel.locator('summary').click()
    assert.ok(await panel.getByText(/QuickBooks Online/).isVisible())
    await search.fill('zzzz-no-question')
    assert.ok(await page.getByRole('status').isVisible())
    await page.getByRole('button', { name: 'Clear search', exact: true }).click()
    assert.equal(await search.inputValue(), '')
    await general.focus()
    await page.keyboard.press('Home')
    assert.equal(await page.getByRole('tab', { name: 'Setting up FAQs', exact: true }).getAttribute('aria-selected'), 'true')
    assert.equal(await page.getByRole('tabpanel').locator('details').count(), 5)
    for (const href of await page.locator('.hm-page a[href^="/"]').evaluateAll(links => links.map(a => a.getAttribute('href')))) assert.ok(routes.has(href), 'Valid destination: ' + href)
    const nestedScroll = await page.locator('.hm-page').evaluate(root => [...root.querySelectorAll('*')].filter(e => ['auto', 'scroll'].includes(getComputedStyle(e).overflowY) && e.scrollHeight > e.clientHeight + 2).length)
    assert.equal(nestedScroll, 0, 'One document scroll area')
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: resolve(output, 'hero-' + width + '.png'), animations: 'disabled' })
    console.log(`PASS ${width}px: centered hero/video, original assets, carousel, FAQ search/keyboard controls, links, reduced motion, and single scroll/footer`)
    await page.close()
  }
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(base + '/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('dialog').waitFor()
  assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden')
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden')
  await page.getByRole('button', { name: 'Watch our introduction', exact: true }).click()
  await page.waitForFunction(() => { const video = document.querySelector('.hm-video-shell video'); return video.readyState >= 2 && !video.paused }, {}, { timeout: 30000 })
  await page.getByRole('button', { name: 'Pause introduction video', exact: true }).click()
  assert.ok(await page.locator('video').evaluate(video => video.paused))
  await page.getByRole('button', { name: 'Play introduction video', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('video').paused)
  await page.getByRole('button', { name: 'Pause introduction video', exact: true }).click()
  const chapters = page.locator('.hm-approach-chapters section')
  for (let index = 0; index < await chapters.count(); index++) {
    await chapters.nth(index).scrollIntoViewIfNeeded()
    await page.waitForFunction(index => Number(getComputedStyle(document.querySelectorAll('.hm-approach-chapters section')[index].parentElement).opacity) > 0.99, index)
  }
  const challenge = page.getByRole('region', { name: 'Business challenges', exact: true })
  await challenge.scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: 'Pause automatic challenge slides', exact: true }).click()
  assert.ok(await page.getByRole('button', { name: 'Resume automatic challenge slides', exact: true }).isVisible())
  await page.getByRole('link', { name: 'Speak with our team', exact: true }).click()
  await page.waitForURL('**/contact')
  assert.deepEqual(errors, [])
  console.log('PASS original video playback/pause, modal dismissal and scroll restoration, live scroll reveals, carousel pause, contact CTA, and no runtime errors')
  await page.close()
} finally { await browser.close() }
